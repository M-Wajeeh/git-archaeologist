import React, { useEffect, useState } from 'react';
import { FileHotspot, DiagnosisResult } from '../types';
import { diagnoseHotspot } from '../services/api';
import {
  X,
  GitCommit,
  Users,
  FileCode2,
  Calendar,
  AlertTriangle,
  Lightbulb,
  Layers,
  Copy,
  Check,
  ExternalLink,
  CheckSquare,
  Square,
  Sparkles,
} from 'lucide-react';

interface InspectorDrawerProps {
  file: FileHotspot | null;
  activeRepo?: string;
  onClose: () => void;
}

export const InspectorDrawer: React.FC<InspectorDrawerProps> = ({ file, activeRepo = '', onClose }) => {
  const [diagnosis, setDiagnosis] = useState<DiagnosisResult | null>(null);
  const [isLoadingDiagnosis, setIsLoadingDiagnosis] = useState<boolean>(false);
  const [diagError, setDiagError] = useState<string | null>(null);
  const [copiedDiagnosis, setCopiedDiagnosis] = useState<boolean>(false);
  const [copiedPath, setCopiedPath] = useState<boolean>(false);
  const [completedSteps, setCompletedSteps] = useState<Record<number, boolean>>({});

  // Close on Escape key press
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        onClose();
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [onClose]);

  // Request AI diagnosis when a file is opened
  useEffect(() => {
    if (!file) {
      setDiagnosis(null);
      setCompletedSteps({});
      return;
    }

    let isMounted = true;
    setIsLoadingDiagnosis(true);
    setDiagError(null);
    setCompletedSteps({});

    diagnoseHotspot(file)
      .then((res) => {
        if (isMounted) setDiagnosis(res);
      })
      .catch((err) => {
        if (isMounted) setDiagError(err.message || 'Unable to generate diagnosis');
      })
      .finally(() => {
        if (isMounted) setIsLoadingDiagnosis(false);
      });

    return () => {
      isMounted = false;
    };
  }, [file]);

  if (!file) return null;

  const handleCopyPath = () => {
    navigator.clipboard.writeText(file.path);
    setCopiedPath(true);
    setTimeout(() => setCopiedPath(false), 1500);
  };

  const handleCopyDiagnosis = () => {
    if (!diagnosis) return;
    const markdown = [
      `### Architectural Diagnosis: \`${file.path}\``,
      `**Debt Score**: ${file.debt_score}/100 | **Risk**: ${file.risk_level.toUpperCase()}`,
      `**Metrics**: ${file.churn_count} commits, ${file.unique_authors} authors, ${file.lines} lines of code`,
      '',
      `#### Why This is Debt:`,
      diagnosis.why_it_is_debt,
      '',
      `#### Recommended Refactoring Steps:`,
      ...diagnosis.refactoring_steps.map((step, idx) => `${idx + 1}. ${step}`),
      '',
      `*Generated by GitArchaeologist (${diagnosis.source})*`,
    ].join('\n');

    navigator.clipboard.writeText(markdown);
    setCopiedDiagnosis(true);
    setTimeout(() => setCopiedDiagnosis(false), 2000);
  };

  const toggleStep = (idx: number) => {
    setCompletedSteps((prev) => ({
      ...prev,
      [idx]: !prev[idx],
    }));
  };

  const getPriorityLabel = (score: number) => {
    if (score >= 85) return { label: 'P0 - Immediate', color: 'text-red-700 border-red-300 bg-red-50' };
    if (score >= 70) return { label: 'P1 - High', color: 'text-orange-700 border-orange-300 bg-orange-50' };
    if (score >= 40) return { label: 'P2 - Moderate', color: 'text-amber-800 border-amber-300 bg-amber-50' };
    return { label: 'P3 - Low', color: 'text-emerald-800 border-emerald-300 bg-emerald-50' };
  };

  const priority = getPriorityLabel(file.debt_score);
  const cleanRepo = activeRepo.replace(/^https?:\/\/github\.com\//, '').replace(/\.git$/, '');
  const githubFileUrl = cleanRepo ? `https://github.com/${cleanRepo}/blob/HEAD/${file.path}` : null;

  return (
    <div className="fixed inset-0 z-50 overflow-hidden">
      {/* Soft Backdrop */}
      <div
        onClick={onClose}
        className="absolute inset-0 bg-black/40 backdrop-blur-2xs transition-opacity"
      />

      {/* Drawer Panel */}
      <div className="fixed inset-y-0 right-0 max-w-full flex pl-10">
        <aside className="w-screen max-w-xl bg-white border-l border-zinc-200 text-zinc-900 flex flex-col shadow-2xl overflow-y-auto">
          {/* Header */}
          <div className="px-6 py-4 border-b border-zinc-200 flex items-start justify-between gap-4 bg-zinc-50 sticky top-0 z-10">
            <div className="min-w-0 flex-1">
              <div className="flex items-center gap-2 flex-wrap">
                <span className="text-xs font-mono px-2 py-0.5 rounded bg-white text-zinc-800 border border-zinc-300 font-semibold shadow-2xs">
                  Debt Score: {file.debt_score}/100
                </span>
                <span className={`text-xs font-mono px-2 py-0.5 rounded border font-semibold ${priority.color}`}>
                  {priority.label}
                </span>
              </div>
              <h2 className="text-base font-mono font-bold text-zinc-900 mt-2 truncate">
                {file.path.split('/').pop()}
              </h2>
              <div className="flex items-center gap-2 mt-0.5">
                <p className="text-xs font-mono text-zinc-500 truncate" title={file.path}>
                  {file.path}
                </p>
                <button
                  onClick={handleCopyPath}
                  title="Copy path"
                  className="text-zinc-400 hover:text-zinc-700 p-0.5 rounded"
                >
                  {copiedPath ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
                </button>
              </div>
            </div>

            <div className="flex items-center gap-1.5 shrink-0">
              {githubFileUrl && (
                <a
                  href={githubFileUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  title="View on GitHub"
                  className="text-zinc-500 hover:text-zinc-800 p-1.5 rounded-md hover:bg-zinc-200 transition-colors border border-zinc-200 shadow-2xs inline-flex items-center gap-1 text-xs font-mono"
                >
                  <ExternalLink className="w-3.5 h-3.5" />
                  <span className="hidden sm:inline">GitHub</span>
                </a>
              )}
              <button
                onClick={onClose}
                className="text-zinc-400 hover:text-zinc-700 p-1.5 rounded-md hover:bg-zinc-200 transition-colors"
                title="Close Drawer (Esc)"
              >
                <X className="w-5 h-5" />
              </button>
            </div>
          </div>

          {/* Drawer Body */}
          <div className="p-6 space-y-6 flex-1">
            {/* Micro Stats Grid */}
            <div className="grid grid-cols-3 gap-3">
              <div className="bg-zinc-50 border border-zinc-200 rounded-lg p-3">
                <div className="flex items-center gap-1.5 text-zinc-500 text-[11px] font-mono">
                  <GitCommit className="w-3.5 h-3.5 text-zinc-400" />
                  <span>TOTAL CHURN</span>
                </div>
                <p className="text-xl font-mono font-bold text-zinc-900 mt-1">
                  {file.churn_count}
                </p>
                <p className="text-[10px] text-zinc-400 mt-0.5">in last 50 commits</p>
              </div>

              <div className="bg-zinc-50 border border-zinc-200 rounded-lg p-3">
                <div className="flex items-center gap-1.5 text-zinc-500 text-[11px] font-mono">
                  <Users className="w-3.5 h-3.5 text-zinc-400" />
                  <span>AUTHORS</span>
                </div>
                <p className="text-xl font-mono font-bold text-zinc-900 mt-1">
                  {file.unique_authors}
                </p>
                <p className="text-[10px] text-zinc-400 mt-0.5">contributors</p>
              </div>

              <div className="bg-zinc-50 border border-zinc-200 rounded-lg p-3">
                <div className="flex items-center gap-1.5 text-zinc-500 text-[11px] font-mono">
                  <FileCode2 className="w-3.5 h-3.5 text-zinc-400" />
                  <span>LINES</span>
                </div>
                <p className="text-xl font-mono font-bold text-zinc-900 mt-1">
                  {file.lines.toLocaleString()}
                </p>
                <p className="text-[10px] text-zinc-400 mt-0.5">approx loc</p>
              </div>
            </div>

            {/* AI Architectural Diagnosis Card */}
            <div className="bg-white border border-zinc-200 rounded-lg p-4 shadow-2xs space-y-3">
              <div className="flex items-center justify-between border-b border-zinc-200 pb-2.5">
                <div className="flex items-center gap-2">
                  <div className="w-5 h-5 rounded bg-orange-50 border border-orange-200 flex items-center justify-center text-orange-600">
                    <Sparkles className="w-3 h-3" />
                  </div>
                  <h3 className="font-mono font-bold text-xs uppercase text-zinc-900 tracking-tight">
                    Architectural Diagnosis
                  </h3>
                </div>

                <div className="flex items-center gap-2">
                  {diagnosis && (
                    <button
                      onClick={handleCopyDiagnosis}
                      className="inline-flex items-center gap-1 text-[11px] font-mono text-zinc-600 hover:text-zinc-900 px-2 py-0.5 rounded border border-zinc-200 hover:bg-zinc-50 transition-colors shadow-2xs"
                      title="Copy diagnosis as markdown"
                    >
                      {copiedDiagnosis ? (
                        <>
                          <Check className="w-3 h-3 text-emerald-600" />
                          <span className="text-emerald-700 font-semibold">Copied</span>
                        </>
                      ) : (
                        <>
                          <Copy className="w-3 h-3" />
                          <span>Copy Markdown</span>
                        </>
                      )}
                    </button>
                  )}
                  {diagnosis && (
                    <span className="text-[10px] font-mono text-zinc-500 bg-zinc-100 px-1.5 py-0.5 rounded border border-zinc-200">
                      {diagnosis.source === 'heuristic_fallback' ? 'Heuristic Engine' : 'Gemini 1.5 Flash'}
                    </span>
                  )}
                </div>
              </div>

              {isLoadingDiagnosis ? (
                <div className="py-6 flex flex-col items-center justify-center text-center space-y-2">
                  <div className="w-5 h-5 border-2 border-orange-600 border-t-transparent rounded-full animate-spin" />
                  <p className="text-xs font-mono text-zinc-500">
                    Consulting architectural diagnostic engine...
                  </p>
                </div>
              ) : diagError ? (
                <div className="p-3 bg-red-50 border border-red-200 rounded text-xs text-red-700">
                  {diagError}
                </div>
              ) : diagnosis ? (
                <div className="space-y-4 text-xs">
                  {/* Why this is debt */}
                  <div className="space-y-1">
                    <div className="flex items-center gap-1.5 text-zinc-700 font-mono font-semibold text-[11px]">
                      <AlertTriangle className="w-3.5 h-3.5 text-amber-600" />
                      <span>WHY THIS IS DEBT</span>
                    </div>
                    <p className="text-zinc-800 leading-relaxed bg-zinc-50 p-3 rounded border border-zinc-200 text-xs">
                      {diagnosis.why_it_is_debt}
                    </p>
                  </div>

                  {/* Refactoring Steps Checklist */}
                  <div className="space-y-1.5">
                    <div className="flex items-center justify-between">
                      <div className="flex items-center gap-1.5 text-zinc-700 font-mono font-semibold text-[11px]">
                        <Lightbulb className="w-3.5 h-3.5 text-orange-600" />
                        <span>ACTIONABLE REFACTORING PLAN</span>
                      </div>
                      <span className="text-[10px] font-mono text-zinc-400">
                        Click checkbox to track progress
                      </span>
                    </div>

                    <div className="space-y-2">
                      {diagnosis.refactoring_steps.map((step, idx) => {
                        const isDone = completedSteps[idx];
                        return (
                          <div
                            key={idx}
                            onClick={() => toggleStep(idx)}
                            className={`p-2.5 rounded border transition-colors cursor-pointer flex items-start gap-2.5 ${
                              isDone
                                ? 'bg-emerald-50/70 border-emerald-200 text-emerald-900'
                                : 'bg-white border-zinc-200 text-zinc-800 hover:border-zinc-300 hover:bg-zinc-50'
                            }`}
                          >
                            <button
                              type="button"
                              className="mt-0.5 text-zinc-400 hover:text-zinc-700 shrink-0"
                            >
                              {isDone ? (
                                <CheckSquare className="w-4 h-4 text-emerald-600" />
                              ) : (
                                <Square className="w-4 h-4" />
                              )}
                            </button>
                            <div className="flex-1">
                              <span className="text-[11px] font-mono font-bold mr-1.5 text-zinc-500">
                                Step {idx + 1}:
                              </span>
                              <span className={`text-xs ${isDone ? 'line-through text-zinc-500' : ''}`}>
                                {step}
                              </span>
                            </div>
                          </div>
                        );
                      })}
                    </div>
                  </div>
                </div>
              ) : null}
            </div>

            {/* Recent File Commits Touchpoint Stream */}
            <div className="space-y-2.5">
              <div className="flex items-center gap-2 text-zinc-700 font-mono font-semibold text-xs">
                <Layers className="w-3.5 h-3.5 text-zinc-500" />
                <span>RECENT TOUCHPOINTS ({file.recent_commits?.length || 0})</span>
              </div>

              <div className="space-y-2 font-mono text-xs">
                {file.recent_commits && file.recent_commits.length > 0 ? (
                  file.recent_commits.map((c, idx) => (
                    <div
                      key={c.hash || idx}
                      className="p-3 bg-zinc-50 border border-zinc-200 rounded-md space-y-1 hover:border-zinc-300 transition-colors"
                    >
                      <div className="flex items-center justify-between text-[11px] text-zinc-500">
                        <span className="px-1.5 py-0.5 bg-white border border-zinc-200 rounded font-bold text-zinc-800">
                          {c.hash.slice(0, 7)}
                        </span>
                        <div className="flex items-center gap-1 text-zinc-400">
                          <Calendar className="w-3 h-3" />
                          <span>{c.date || 'Recent'}</span>
                        </div>
                      </div>
                      <p className="text-zinc-800 font-sans text-xs leading-normal">
                        {c.message}
                      </p>
                      <div className="flex items-center justify-between text-[10px] text-zinc-400 pt-0.5">
                        <span>by {c.author}</span>
                      </div>
                    </div>
                  ))
                ) : (
                  <p className="text-xs text-zinc-400 italic">No touchpoints recorded for this file.</p>
                )}
              </div>
            </div>
          </div>
        </aside>
      </div>
    </div>
  );
};
